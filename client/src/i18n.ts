const catalogs: Record<Locale, LocaleCatalog> = { 'zh-Hant': zhHant, 'zh-Hans': zhHans, en }
const localeStorageKey = 'imr.locale'
const localeTags: Record<Locale, string> = { 'zh-Hant': 'zh-TW', 'zh-Hans': 'zh-CN', en: 'en' }
const listeners: Array<() => void> = []

function readLocale(): Locale {
  try {
    const saved = window.localStorage.getItem(localeStorageKey)
    if (saved === 'zh-Hant' || saved === 'zh-Hans' || saved === 'en') return saved
  } catch {
    // Ignore storage restrictions and use the default locale.
  }
  return 'zh-Hant'
}

let locale: Locale = readLocale()

export interface LocalizedMessage {
  key: TranslationKey
  params?: TranslationParams
}

export function message(key: TranslationKey, params?: TranslationParams): LocalizedMessage {
  return { key, params }
}

export function resolveMessage(value: string | LocalizedMessage): string {
  return typeof value === 'string' ? value : t(value.key, value.params)
}

export function getLocale(): Locale {
  return locale
}

export function setLocale(next: Locale): void {
  if (next === locale) return
  locale = next
  try {
    window.localStorage.setItem(localeStorageKey, locale)
  } catch {
    // A private browsing policy should not prevent language switching.
  }
  document.documentElement.lang = localeTags[locale]
  listeners.forEach((listener) => listener())
}

export function onLocaleChange(listener: () => void): void {
  listeners.push(listener)
}

export function t(key: TranslationKey | string, params: TranslationParams = {}): string {
  const template = catalogs[locale][key as TranslationKey] ?? catalogs['zh-Hant'][key as TranslationKey] ?? key
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => {
    const value = params[name]
    if (typeof value === 'function') return value()
    if (value && typeof value === 'object') return resolveMessage(value)
    return String(value ?? '')
  })
}

export function formatTime(timestamp: number): string {
  return new Date(timestamp).toLocaleTimeString(localeTags[locale])
}

export function formatDateTime(timestampSeconds: number): string {
  return new Date(timestampSeconds * 1000).toLocaleString(localeTags[locale], {
    year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
  })
}

export function applyTranslations(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n ?? '')
  })
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder ?? '')
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt ?? ''))
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((element) => {
    element.title = t(element.dataset.i18nTitle ?? '')
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel ?? ''))
  })
  document.documentElement.lang = localeTags[locale]
  document.title = t('app.title')
}
